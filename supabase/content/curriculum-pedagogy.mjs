const organized = new Map(ORGANIZATION.map(([id,role,module])=>[id,{role,module}]));
const levels = Object.keys(MODULES);
const existing = CURRENT_CURRICULUM.map(l=>({...l,...organized.get(l.id),previousOrder:l.order}));
const added = COURSES.flatMap(c=>c.lessons.map((l,i)=>({
  id:l.id,courseId:c.id,level:c.level,role:'base',core:true,
  module: LESSON_CONTENT.filter(x=>x.level===c.level)[i].module,
  reason: l.description, previousOrder:i,
})));
// Apresentação existente primeiro; depois a introdução simples antes dos pacotes de contraste.
const priority = l => l.id==='lesson-first-sentences-a1-01' ? -2
  : l.id==='lesson-tenses-b1-01' ? -2 : l.id==='lesson-tenses-b1-03' ? -2
    : l.id==='lesson-grammar-b2-06' ? -2 : l.id.startsWith('lesson-pedagogy-') ? -1 : 0;
const sorted=[...existing,...added].sort((a,b)=>levels.indexOf(a.level)-levels.indexOf(b.level)
  || a.module-b.module || priority(a)-priority(b) || a.previousOrder-b.previousOrder);
const previousBase=new Map();
export const PEDAGOGY_CURRICULUM=sorted.map((l,i)=>{
  const requires=previousBase.has(l.level)?[previousBase.get(l.level)]:[];
  if(l.role==='base')previousBase.set(l.level,l.id);
  return {id:l.id,courseId:l.courseId,level:l.level,role:l.role,core:l.role==='base',
    module:MODULES[l.level][l.module-1],moduleOrder:l.module,order:(i+1)*10,requires,reason:l.reason};
});
